#!/usr/bin/env python3
# SPDX-License-Identifier: AGPL-3.0-or-later
"""
gen_requirements.py — regenerate the repo-root Python dependency manifests as the
UNION of every other requirements.txt in the project.

Outputs:
  requirements.txt  pip-compatible view (also consumed by older tooling)
  pyproject.toml    PEP 621 project metadata for uv / pip
  uv.lock           optional, refreshed with --lock (committed for reproducibility)

It is run automatically by:
  - the git pre-commit hook (.githooks/pre-commit), so a commit that touches any
    sub-requirements.txt re-syncs the root files, and
  - auto.sh, so the root files are fresh every time you run the toolkit.

Dedup is by package name (case-insensitive); the first spec seen for a name wins.
An unpinned entry means "latest"; version specifiers (==, >=, ~=, ...) are kept.
The pseudo-specifiers "pkg@latest" and "pkg==latest" are normalized to an
unpinned "pkg" so uv/pip resolve the latest release.

Refresh the lock after changing dependencies:
    python3 scripts/gen_requirements.py --lock
    python3 scripts/gen_requirements.py --lock --upgrade   # bump locked versions
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REQ_OUT = os.path.join(ROOT, "requirements.txt")
PYPROJECT_OUT = os.path.join(ROOT, "pyproject.toml")
SKIP_DIRS = {".git", "__pycache__", "venv", ".venv", "build", "node_modules"}
_SPLIT = re.compile(r"[<>=!~;\[\s]")
_LATEST = re.compile(
    r"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*(?:\[[^\]]+\])?)\s*(?:==|===|@)\s*latest\s*$",
    re.IGNORECASE,
)


def iter_req_files():
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        if "requirements.txt" not in filenames:
            continue
        full = os.path.join(dirpath, "requirements.txt")
        if os.path.abspath(full) == os.path.abspath(REQ_OUT):
            continue  # never read our own output back in
        yield full


def clean_spec(line):
    """Return a usable requirement line, or "" for comments/options/URLs."""
    line = line.split("#", 1)[0].strip()
    if not line:
        return ""
    # Pip options (-r, --index-url, -e ...) and direct URLs cannot be represented
    # as plain PEP 621 dependency strings without package metadata.
    if line.startswith(("-", "http://", "https://", "git+", "file:")):
        return ""
    match = _LATEST.match(line)
    if match:
        return match.group("name")  # "pkg@latest" / "pkg==latest" -> latest release
    return line


def pkg_name(spec):
    return _SPLIT.split(spec, 1)[0].strip().lower()


def write_requirements(specs):
    lines = [specs[k] for k in sorted(specs)]
    with open(REQ_OUT, "w", encoding="utf-8") as fh:
        fh.write("# SPDX-License-Identifier: AGPL-3.0-or-later\n")
        fh.write("# AUTO-GENERATED — do not edit by hand.\n")
        fh.write("# Union of every other requirements.txt in this repo, regenerated by\n")
        fh.write("# scripts/gen_requirements.py (via the .githooks/pre-commit hook and auto.sh).\n")
        fh.write("# Install every Python exploit dependency at once:\n")
        fh.write('#   uv pip install --python "$(command -v python3)" --prefix ~/.local -r requirements.txt\n')
        fh.write("#   python3 -m pip install --user --break-system-packages -r requirements.txt\n")
        fh.write("# Reproducible locked venv: uv sync (uses pyproject.toml + uv.lock)\n")
        fh.write("# Unpinned packages resolve to the latest release; versions are honored.\n")
        fh.write("# (ExploitFarm's server is separate — https://github.com/Pwnzer0tt1/exploitfarm)\n")
        for line in lines:
            fh.write(line + "\n")


def write_pyproject(specs):
    lines = [
        "# SPDX-License-Identifier: AGPL-3.0-or-later",
        "# AUTO-GENERATED — do not edit by hand.",
        "# Generated from every subproject requirements.txt by scripts/gen_requirements.py.",
        "# Unpinned requirements resolve to the latest release; version specs are honored.",
        "# Refresh the lockfile: python3 scripts/gen_requirements.py --lock --upgrade",
        "# Reproducible install:  uv sync",
        "",
        "[project]",
        'name = "vulnbox-autoconfig"',
        "# The repo release version lives in VERSION.json. uv only needs a valid",
        "# project version here; keep it stable so the lock changes only with deps.",
        'version = "0.0.0"',
        'description = "Python exploit dependencies for the Vulnbox-AutoConfig toolkit."',
        'requires-python = ">=3.10"',
        "dependencies = [",
    ]
    for name in sorted(specs):
        lines.append(f"    {json.dumps(specs[name])},")
    lines += [
        "]",
        "",
        "[tool.uv]",
        "# This repo ships scripts, not an importable Python package.",
        "package = false",
        "",
    ]
    with open(PYPROJECT_OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def refresh_lock(upgrade=False):
    if not shutil.which("uv"):
        print("[gen_requirements] uv not found — skipping uv.lock refresh.", file=sys.stderr)
        return False
    cmd = ["uv", "lock"]
    if upgrade:
        cmd.append("--upgrade")
    print(f"[gen_requirements] {' '.join(cmd)}")
    return subprocess.run(cmd, cwd=ROOT, check=False).returncode == 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--lock",
        action="store_true",
        help="refresh uv.lock after writing the manifests (requires uv and network)",
    )
    ap.add_argument(
        "--upgrade",
        action="store_true",
        help="with --lock, allow uv to upgrade locked dependency versions",
    )
    args = ap.parse_args()

    seen = {}  # name -> first full spec line
    for f in sorted(iter_req_files()):
        with open(f, encoding="utf-8") as fh:
            for raw in fh:
                line = clean_spec(raw)
                if not line:
                    continue
                name = pkg_name(line)
                if name and name not in seen:
                    seen[name] = line

    write_requirements(seen)
    write_pyproject(seen)
    print(f"[gen_requirements] wrote {REQ_OUT} ({len(seen)} packages)")
    print(f"[gen_requirements] wrote {PYPROJECT_OUT}")

    if args.lock and not refresh_lock(args.upgrade):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
